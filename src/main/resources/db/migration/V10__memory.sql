-- v0.0.0 Memory: metadata index of Obsidian vault notes (body lives in the vault file).

CREATE TABLE memory_note (
    id                 VARCHAR(40)   NOT NULL PRIMARY KEY,
    scope              VARCHAR(16)   NOT NULL,
    owner_agent_id     VARCHAR(80)   NOT NULL,
    group_id           VARCHAR(80)   NULL,
    kind               VARCHAR(40)   NOT NULL,
    title              VARCHAR(300)  NOT NULL,
    file_path          VARCHAR(600)  NOT NULL,
    tags               JSON          NULL,
    links              JSON          NULL,
    source             VARCHAR(1000) NULL,
    confidence         DOUBLE        NOT NULL DEFAULT 0.5,
    invalidated        TINYINT(1)    NOT NULL DEFAULT 0,
    superseded_by      VARCHAR(40)   NULL,
    invalidated_reason VARCHAR(1000) NULL,
    content_hash       CHAR(64)      NOT NULL,
    scope_key          VARCHAR(120)  NOT NULL,
    body_excerpt       VARCHAR(2000) NULL,
    index_pending      TINYINT(1)    NOT NULL DEFAULT 0,
    created_at         DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    created_by         VARCHAR(80)   NOT NULL,
    updated_at         DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    updated_by         VARCHAR(80)   NOT NULL,
    row_version        INT           NOT NULL DEFAULT 0,
    deleted            TINYINT(1)    NOT NULL DEFAULT 0,
    deleted_at         DATETIME(3)   NULL,
    deleted_by         VARCHAR(80)   NULL,
    UNIQUE KEY uk_memory_dedup (owner_agent_id, scope_key, content_hash),
    INDEX idx_memory_scope_owner (scope, owner_agent_id),
    INDEX idx_memory_group (group_id),
    INDEX idx_memory_kind (kind),
    INDEX idx_memory_invalidated (invalidated),
    INDEX idx_memory_pending (index_pending, id),
    FULLTEXT INDEX ft_memory_text (title, body_excerpt)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;
